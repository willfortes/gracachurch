-- Guia de negócios e serviços dos membros
CREATE TABLE businesses (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  slug VARCHAR(140) NOT NULL UNIQUE,
  name VARCHAR(120) NOT NULL,
  category VARCHAR(30) NOT NULL DEFAULT 'outros',
  description TEXT NOT NULL,
  tags VARCHAR(400) NOT NULL DEFAULT '',
  owner_name VARCHAR(120) NOT NULL,
  whatsapp VARCHAR(30) NOT NULL,
  phone VARCHAR(30) NULL,
  instagram VARCHAR(80) NULL,
  website VARCHAR(200) NULL,
  email VARCHAR(160) NULL,
  neighborhood VARCHAR(80) NOT NULL DEFAULT '',
  city VARCHAR(80) NOT NULL DEFAULT 'Palhoça',
  address VARCHAR(200) NULL,
  show_address TINYINT(1) NOT NULL DEFAULT 0,
  lat DECIMAL(9,6) NULL,
  lng DECIMAL(9,6) NULL,
  service_mode SET('local','domicilio','online') NOT NULL DEFAULT 'local',
  service_area VARCHAR(160) NULL,
  hours VARCHAR(160) NULL,
  logo VARCHAR(160) NULL,
  status ENUM('pendente','aprovado','recusado') NOT NULL DEFAULT 'pendente',
  needs_review TINYINT(1) NOT NULL DEFAULT 0,
  featured TINYINT(1) NOT NULL DEFAULT 0,
  edit_token CHAR(40) NOT NULL,
  search_text TEXT NULL,
  review_note VARCHAR(400) NULL,
  ip_hash CHAR(64) NOT NULL DEFAULT '',
  views INT UNSIGNED NOT NULL DEFAULT 0,
  approved_at DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_status (status, category),
  UNIQUE KEY uq_token (edit_token)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
